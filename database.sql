-- MEDIA RATINGS PLATFORM (MRP)
-- PostgreSQL Database Schema

-- 1. USERS

CREATE TABLE users (
    user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    email VARCHAR(255) UNIQUE,
    favorite_genre VARCHAR(100)
);


-- 2. MEDIA

CREATE TABLE media (
    media_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    description TEXT NOT NULL,
    media_type VARCHAR(20) NOT NULL,
    release_year INTEGER NOT NULL,
    age_restriction INTEGER NOT NULL,
    creator_user_id INTEGER NOT NULL,
    genres TEXT[],

    CONSTRAINT fk_media_creator
       FOREIGN KEY (creator_user_id)
           REFERENCES users(user_id),

    CONSTRAINT chk_media_type
       CHECK (media_type IN ('Movie', 'Serie', 'Game')),

    CONSTRAINT chk_age_restriction
       CHECK (age_restriction >= 0)
);


-- 3. GENRES

CREATE TABLE genres (
    genre_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE
);


-- 4. MEDIA_GENRES

CREATE TABLE media_genres (
    media_id INTEGER NOT NULL,
    genre_id INTEGER NOT NULL,

    PRIMARY KEY (media_id, genre_id),

    FOREIGN KEY (media_id)
      REFERENCES media(media_id)
      ON DELETE CASCADE,

    FOREIGN KEY (genre_id)
      REFERENCES genres(genre_id)
      ON DELETE CASCADE
);


-- 5. RATINGS

CREATE TABLE ratings (
    rating_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL,
    media_id INTEGER NOT NULL,
    stars INTEGER NOT NULL,
    comment TEXT,
    timestamp TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    is_confirmed BOOLEAN NOT NULL DEFAULT FALSE,

    FOREIGN KEY (user_id)
     REFERENCES users(user_id),

    FOREIGN KEY (media_id)
     REFERENCES media(media_id)
     ON DELETE CASCADE,

    CONSTRAINT chk_rating_stars
     CHECK (stars >= 1 AND stars <= 5)
);


-- 6. FAVORITES

CREATE TABLE favorites (
    user_id INTEGER NOT NULL,
    media_id INTEGER NOT NULL,

    PRIMARY KEY (user_id, media_id),

    FOREIGN KEY (user_id)
       REFERENCES users(user_id)
       ON DELETE CASCADE,

    FOREIGN KEY (media_id)
       REFERENCES media(media_id)
       ON DELETE CASCADE
);


-- 7. RATING_LIKES

CREATE TABLE rating_likes (
    user_id INTEGER NOT NULL,
    rating_id INTEGER NOT NULL,

    PRIMARY KEY (user_id, rating_id),

    FOREIGN KEY (user_id)
      REFERENCES users(user_id)
      ON DELETE CASCADE,

    FOREIGN KEY (rating_id)
      REFERENCES ratings(rating_id)
      ON DELETE CASCADE
);


-- 8. AUTH_TOKENS

CREATE TABLE auth_tokens (
    token_hash TEXT PRIMARY KEY,
    user_id INTEGER NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,

    FOREIGN KEY (user_id)
     REFERENCES users(user_id)
     ON DELETE CASCADE
);